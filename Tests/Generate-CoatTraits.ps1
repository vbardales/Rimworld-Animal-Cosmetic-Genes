<#
.SYNOPSIS
  Writes the coat tint traits and the gene to trait table of Animal Cosmetic Genes from a gene catalogue.

.DESCRIPTION
  One cosmetic colour gene = one Animal Traits System trait (a HediffDef whose skinColorTint is the gene's own colour)
  plus one row of the GeneTraitMapDef that tells AnimalTraitGrant which trait the gene gives. New gene or new mod:
  update the catalogue, run this script, commit the two generated files. Nothing is edited by hand.

  Input: the gene catalogue of Nelim's Pickle Tools (docs/catalogues/genes.md, generated from the mods on disk). Only the
  sections "Skin colours" and "Hair colours" are read; table rows are "| Mod | defName#RRGGBB, defName#RRGGBB |".
  The colour after # is the RGB read from the gene's own def. Eye colours need a render node per species (not a tint),
  look genes carry no colour: both are skipped.

  Output (UTF-8, LF, overwritten, each starts with a GENERATED line):
    Mod/Defs/Hediffs_GeneTints.xml   one HediffDef AnimalTrait_<gene defName> per gene
    Mod/Defs/GeneTraitMap.xml        one GeneTraitMapDef listing gene defName -> trait

  The traits carry no exclusiveWithAnimalTrait list (241 traits would need 58 000 entries): AnimalTraitGrant refuses a
  second coat tint itself. They are never drawn at random (defaultWeight 0) and are inherited (inheritChance).

    powershell -NoProfile -ExecutionPolicy Bypass -File Tests\Generate-CoatTraits.ps1
    powershell -NoProfile -ExecutionPolicy Bypass -File Tests\Generate-CoatTraits.ps1 -Catalogue <genes.md> -Strength 0.4

  Pure ASCII on purpose (Windows PowerShell 5.1 reads a BOM-less .ps1 as ANSI).
#>
param(
  [string]$Catalogue = 'C:\Users\nelim\Documents\rimworld\PickleTools\ColonistRace\docs\catalogues\genes.md',
  [string]$ModRoot = (Split-Path $PSScriptRoot -Parent),
  [double]$Strength = 0.4,
  [int]$InheritChance = 40
)
$ErrorActionPreference = 'Stop'
$inv = [Globalization.CultureInfo]::InvariantCulture

function Format-Channel([int]$byte) { ($byte / 255.0).ToString('0.###', $inv) }

# "GES_Skin_BananaSplit" -> "banana split", "Skin_Melanin3" -> "melanin 3", "OL_HairSky" -> "sky"
function Get-ColourName([string]$defName) {
  $s = $defName -replace '^(GES|GEH|LYN|OL)_', '' -replace '^(Skin|Hair)_?', ''
  $s = ($s -creplace '([a-z])([A-Z])', '$1 $2') -creplace '([A-Za-z])([0-9])', '$1 $2'
  $s = $s.Replace('_', ' ').ToLowerInvariant().Trim()
  # Misspellings in the other mods' gene names, corrected in the displayed name only
  $s -replace 'chesnut', 'chestnut' -replace 'rosey', 'rosy'
}

if (-not (Test-Path $Catalogue)) { throw "Catalogue not found: $Catalogue" }
$genes = New-Object System.Collections.Generic.List[object]
$seen = @{}
$section = $null
foreach ($line in [IO.File]::ReadAllLines($Catalogue, [Text.Encoding]::UTF8)) {
  if ($line -match '^## (Skin|Hair) colours') { $section = $Matches[1]; continue }
  if ($line -match '^## ') { $section = $null; continue }
  if (-not $section -or $line -notmatch '^\|' -or $line -match '^\|\s*(Mod\s*\||-)') { continue }
  $cells = $line.Split('|')
  $mod = $cells[1].Trim()
  foreach ($item in $cells[2].Split(',')) {
    if ($item.Trim() -notmatch '^(\w+)#([0-9A-Fa-f]{6})$') { continue }
    $name = $Matches[1]
    $hex = $Matches[2]
    if ($seen.ContainsKey($name)) { throw "Gene $name listed twice in $Catalogue" }
    $seen[$name] = $true
    $genes.Add([pscustomobject]@{
      Name = $name; Kind = $section; Mod = $mod; Name2 = (Get-ColourName $name)
      R = [Convert]::ToInt32($hex.Substring(0, 2), 16)
      G = [Convert]::ToInt32($hex.Substring(2, 2), 16)
      B = [Convert]::ToInt32($hex.Substring(4, 2), 16)
    })
  }
}
if ($genes.Count -eq 0) { throw "No gene read from $Catalogue (sections Skin colours, Hair colours)" }

$header = "<!-- GENERATED by Tests/Generate-CoatTraits.ps1 from the gene catalogue ($($genes.Count) genes). Do not edit: run the script. -->"

# Traits
$t = New-Object System.Text.StringBuilder
[void]$t.AppendLine('<?xml version="1.0" encoding="utf-8"?>')
[void]$t.AppendLine('<Defs>')
[void]$t.AppendLine('')
[void]$t.AppendLine("  $header")
[void]$t.AppendLine('  <!-- One Animal Traits System trait per cosmetic colour gene: skinColorTint is the gene colour, never drawn at random')
[void]$t.AppendLine('       (defaultWeight 0), inherited (inheritChance). The defName MUST start with "AnimalTrait_". No stage, so the tint is drawn.')
[void]$t.AppendLine('       No exclusiveWithAnimalTrait list: AnimalTraitGrant refuses a second coat tint. -->')
[void]$t.AppendLine('')
[void]$t.AppendLine('  <HediffDef Name="ACG_GeneTintBase" Abstract="True">')
[void]$t.AppendLine('    <hediffClass>HediffWithComps</hediffClass>')
[void]$t.AppendLine('    <isBad>false</isBad>')
[void]$t.AppendLine('    <makesAlert>false</makesAlert>')
[void]$t.AppendLine('    <forceRenderTreeRecache>true</forceRenderTreeRecache>')
[void]$t.AppendLine('    <skinColorTintStrength>' + $Strength.ToString('0.###', $inv) + '</skinColorTintStrength>')
[void]$t.AppendLine('  </HediffDef>')
foreach ($g in $genes) {
  $tint = '(' + (Format-Channel $g.R) + ', ' + (Format-Channel $g.G) + ', ' + (Format-Channel $g.B) + ', 1)'
  [void]$t.AppendLine('')
  [void]$t.AppendLine('  <HediffDef ParentName="ACG_GeneTintBase">')
  [void]$t.AppendLine("    <defName>AnimalTrait_$($g.Name)</defName>")
  [void]$t.AppendLine("    <label>$($g.Name2) coat</label>")
  [void]$t.AppendLine("    <description>A tint of $($g.Name2) runs through this animal's coat.</description>")
  [void]$t.AppendLine("    <skinColorTint>$tint</skinColorTint>")
  [void]$t.AppendLine('    <modExtensions>')
  [void]$t.AppendLine('      <li Class="AnimalTraitExtension.AnimalTraitExtension">')
  [void]$t.AppendLine('        <isAnimalTrait>true</isAnimalTrait>')
  [void]$t.AppendLine("        <traitName>$($g.Name)</traitName>")
  [void]$t.AppendLine('        <defaultWeight>0</defaultWeight>')
  [void]$t.AppendLine("        <inheritChance>$InheritChance</inheritChance>")
  [void]$t.AppendLine('      </li>')
  [void]$t.AppendLine('    </modExtensions>')
  [void]$t.AppendLine('  </HediffDef>')
}
[void]$t.AppendLine('')
[void]$t.AppendLine('</Defs>')

# Table
$m = New-Object System.Text.StringBuilder
[void]$m.AppendLine('<?xml version="1.0" encoding="utf-8"?>')
[void]$m.AppendLine('<Defs>')
[void]$m.AppendLine('')
[void]$m.AppendLine("  $header")
[void]$m.AppendLine('  <!-- Gene defName to trait. The gene is a text, not a reference: a gene of a mod that is not loaded is simply never found,')
[void]$m.AppendLine('       and genes the game generates from a template (Biotech hair colours, melanin) are found as well. -->')
[void]$m.AppendLine('')
[void]$m.AppendLine('  <AnimalCosmeticGenes.GeneTraitMapDef>')
[void]$m.AppendLine('    <defName>ACG_CoatTintGenes</defName>')
[void]$m.AppendLine('    <mappings>')
$lastMod = $null
foreach ($g in $genes) {
  $label = "$($g.Mod) / $($g.Kind)"
  if ($label -ne $lastMod) { [void]$m.AppendLine("      <!-- $label -->"); $lastMod = $label }
  [void]$m.AppendLine("      <li><gene>$($g.Name)</gene><trait>AnimalTrait_$($g.Name)</trait></li>")
}
[void]$m.AppendLine('    </mappings>')
[void]$m.AppendLine('  </AnimalCosmeticGenes.GeneTraitMapDef>')
[void]$m.AppendLine('')
[void]$m.AppendLine('</Defs>')

$utf8 = New-Object System.Text.UTF8Encoding($false)
[IO.File]::WriteAllText((Join-Path $ModRoot 'Mod\Defs\Hediffs_GeneTints.xml'), $t.ToString().Replace("`r`n", "`n"), $utf8)
[IO.File]::WriteAllText((Join-Path $ModRoot 'Mod\Defs\GeneTraitMap.xml'), $m.ToString().Replace("`r`n", "`n"), $utf8)

# French DefInjected: label and description of every tint trait, from Tests/ColourNames.fr.json (colour name, English -> French)
$fr = Get-Content -LiteralPath (Join-Path $PSScriptRoot 'ColourNames.fr.json') -Raw -Encoding UTF8 | ConvertFrom-Json
$f = New-Object System.Text.StringBuilder
[void]$f.AppendLine('<?xml version="1.0" encoding="utf-8"?>')
[void]$f.AppendLine('<LanguageData>')
[void]$f.AppendLine('')
[void]$f.AppendLine("  $header")
$missing = @()
foreach ($g in $genes) {
  $p = $fr.PSObject.Properties[$g.Name2]
  if (-not $p) { $missing += $g.Name2; continue }
  [void]$f.AppendLine('')
  [void]$f.AppendLine("  <AnimalTrait_$($g.Name).label>pelage $($p.Value)</AnimalTrait_$($g.Name).label>")
  [void]$f.AppendLine("  <AnimalTrait_$($g.Name).description>Le pelage de cet animal est teint$([char]0x00E9) en $($p.Value).</AnimalTrait_$($g.Name).description>")
}
[void]$f.AppendLine('')
[void]$f.AppendLine('</LanguageData>')
$frDir = Join-Path $ModRoot 'Mod\Languages\French\DefInjected\HediffDef'
New-Item -ItemType Directory -Force -Path $frDir | Out-Null
[IO.File]::WriteAllText((Join-Path $frDir 'Hediffs_GeneTints.xml'), $f.ToString().Replace("`r`n", "`n"), $utf8)
if ($missing.Count) { Write-Warning ("No French name for: " + (($missing | Sort-Object -Unique) -join ', ')) }

$genes | Group-Object Kind, Mod | ForEach-Object { '{0,4}  {1}' -f $_.Count, $_.Name }
"Wrote $($genes.Count) traits and mappings under $ModRoot\Mod\Defs"
